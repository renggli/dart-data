import 'package:data/symbolic.dart';

import 'algebra.dart' as algebra;

/// Preset configuration for symbolic mathematical expressions.
class ExpressionPreset {
  final String id;
  final String name;
  final String category;
  final String formula;
  final String description;
  final double defaultMinX;
  final double defaultMaxX;
  final String defaultPointX;
  final String defaultIntA;
  final String defaultIntB;
  final algebra.VariableAssumption defaultAssumption;
  final String defaultRelations;
  final String? defaultMvVars;

  const new({
    required this.id,
    required this.name,
    required this.category,
    required this.formula,
    required this.description,
    this.defaultMinX = -5.0,
    this.defaultMaxX = 5.0,
    this.defaultPointX = '1',
    this.defaultIntA = '0',
    this.defaultIntB = '2',
    this.defaultAssumption = algebra.VariableAssumption.unknown,
    this.defaultRelations = '',
    this.defaultMvVars,
  });

  /// Builds the [Assumptions] context configured for [variables].
  Assumptions buildAssumptions(Iterable<String> variables) {
    final map = <String, algebra.VariableAssumption>{
      for (final v in variables) v: defaultAssumption,
    };
    return algebra
        .buildAssumptions(map, relationsRaw: defaultRelations)
        .assumptions;
  }
}

